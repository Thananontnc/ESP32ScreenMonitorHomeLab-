"""Convert Pringle's sprites (from the Mac app's pringle-mac.sh) into include/sprites.h.

Usage: python3 tools/sprites.py ../MacHomeLabMenuBar/Pringle/pringle-mac.sh
Each sprite becomes a 64x64 RGB565 array. Transparent pixels use the key color 0xF81F.
"""
import base64
import io
import re
import sys
from pathlib import Path

from PIL import Image

KEY = 0xF81F
ORDER = ["RUN0", "RUN1", "RUN2", "RUN3", "SAD", "SLEEP"]


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main():
    src = Path(sys.argv[1]).read_text()
    found = dict(re.findall(r'"([A-Z]+[0-9]?)": "([A-Za-z0-9+/=]+)"', src))
    out = ["// Generated by tools/sprites.py from the Pringle Mac app. Do not edit by hand.",
           "#pragma once", "#include <stdint.h>", "",
           "#define SPRITE_W 64", "#define SPRITE_H 64", f"#define SPRITE_KEY 0x{KEY:04X}", ""]
    for name in ORDER:
        im = Image.open(io.BytesIO(base64.b64decode(found[name]))).convert("RGBA")
        assert im.size == (64, 64), f"{name} is {im.size}, expected 64x64"
        px = []
        for r, g, b, a in im.getdata():
            c = KEY if a < 128 else rgb565(r, g, b)
            if c == KEY and a >= 128:
                c = KEY ^ 0x0020  # keep a real magenta pixel visible
            px.append(c)
        rows = [", ".join(f"0x{c:04X}" for c in px[i:i + 16]) for i in range(0, len(px), 16)]
        out.append(f"static const uint16_t SPR_{name}[64 * 64] = {{\n  " + ",\n  ".join(rows) + "\n};\n")
    out.append("static const uint16_t* const SPR_RUN[4] = { SPR_RUN0, SPR_RUN1, SPR_RUN2, SPR_RUN3 };")
    Path(__file__).resolve().parent.parent.joinpath("include", "sprites.h").write_text("\n".join(out) + "\n")
    print("wrote include/sprites.h")


if __name__ == "__main__":
    main()
